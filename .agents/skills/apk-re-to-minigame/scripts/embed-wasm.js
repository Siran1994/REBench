#!/usr/bin/env node
'use strict';

/**
 * embed-wasm.js - 自动扫描并将项目中的 .wasm 二进制文件转为嵌入式 JS 模块
 * 
 * 解决痛点：
 * 抖音小游戏开发者工具与编译器存在静态文件扩展名白名单，不会打包 .wasm 文件到小游戏虚拟文件系统。
 * 通过本工具将 .wasm 转换为 Base64 内嵌在 scripts/embedded-wasm.js 中，
 * 在启动时通过原生 C++ 提供的 tt.base64ToArrayBuffer (或纯 JS) 极速转回 ArrayBuffer，彻底杜绝找不到 wasm 报错。
 * 
 * 用法:
 *   node embed-wasm.js <minigame_project_dir>
 */

const fs = require('fs');
const path = require('path');

const targetDir = process.argv[2] || '.';
const absTarget = path.resolve(targetDir);

if (!fs.existsSync(absTarget)) {
  console.error(`[Error] 目标目录不存在: ${absTarget}`);
  process.exit(1);
}

// 递归扫描 .wasm 文件
function findWasmFiles(dir) {
  let results = [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === 'node_modules' || e.name === '.git' || e.name === 'scratch') continue;
      results = results.concat(findWasmFiles(full));
    } else if (e.isFile() && e.name.toLowerCase().endsWith('.wasm')) {
      results.push(full);
    }
  }
  return results;
}

const wasmFiles = findWasmFiles(absTarget);

if (wasmFiles.length === 0) {
  console.log(`[Info] 在 ${absTarget} 中未检测到任何 .wasm 文件，无需内嵌。`);
  process.exit(0);
}

console.log(`[Info] 扫描到 ${wasmFiles.length} 个 WASM 文件：`);
const wasmMap = {};
let totalBinaryBytes = 0;

for (const file of wasmFiles) {
  const rel = path.relative(absTarget, file).replace(/\\/g, '/');
  const baseName = path.basename(file);
  const buf = fs.readFileSync(file);
  totalBinaryBytes += buf.length;
  const b64 = buf.toString('base64');
  wasmMap[rel] = {
    baseName,
    size: buf.length,
    b64
  };
  console.log(`  - ${rel} (${(buf.length / 1024).toFixed(1)} KB -> Base64 ${(b64.length / 1024).toFixed(1)} KB)`);
}

const entriesCode = Object.entries(wasmMap).map(([rel, item]) => {
  return `  "${rel}": "${item.b64}",\n  "${item.baseName}": "${item.b64}"`;
}).join(',\n');

const generatedCode = `// Auto-generated embedded WASM binary assets for ByteDance MiniGame
// Generated by embed-wasm.js to bypass file extension packaging whitelist issues.
'use strict';

const WASM_MAP = {
${entriesCode}
};

function decodeBase64ToArrayBuffer(b64) {
  if (typeof tt !== 'undefined' && typeof tt.base64ToArrayBuffer === 'function') {
    try {
      return tt.base64ToArrayBuffer(b64);
    } catch (e) {}
  }
  if (typeof Buffer !== 'undefined') {
    const buf = Buffer.from(b64, 'base64');
    return buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
  }
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  const len = b64.length;
  let bufferLength = b64.length * 0.75;
  if (b64[len - 1] === '=') {
    bufferLength--;
    if (b64[len - 2] === '=') bufferLength--;
  }
  const arrayBuffer = new ArrayBuffer(bufferLength);
  const bytes = new Uint8Array(arrayBuffer);
  let p = 0;
  for (let i = 0; i < len; i += 4) {
    const encoded1 = chars.indexOf(b64[i]);
    const encoded2 = chars.indexOf(b64[i + 1]);
    const encoded3 = chars.indexOf(b64[i + 2]);
    const encoded4 = chars.indexOf(b64[i + 3]);
    bytes[p++] = (encoded1 << 2) | (encoded2 >> 4);
    if (encoded3 !== -1 && b64[i + 2] !== '=') bytes[p++] = ((encoded2 & 15) << 4) | (encoded3 >> 2);
    if (encoded4 !== -1 && b64[i + 3] !== '=') bytes[p++] = ((encoded3 & 3) << 6) | (encoded4 & 63);
  }
  return arrayBuffer;
}

const bufferCache = new Map();

function getWasmBuffer(key) {
  if (!key) return null;
  const cleanKey = String(key).replace(/^\\.\\//, '').replace(/^\\//, '');
  if (bufferCache.has(cleanKey)) {
    return bufferCache.get(cleanKey);
  }
  let b64 = WASM_MAP[cleanKey];
  if (!b64) {
    const base = cleanKey.split('/').pop();
    b64 = WASM_MAP[base];
  }
  if (!b64) return null;
  const buf = decodeBase64ToArrayBuffer(b64);
  bufferCache.set(cleanKey, buf);
  return buf;
}

module.exports = {
  getWasmBuffer,
  getNoiseWasmBuffer() {
    return getWasmBuffer('noise.wasm');
  },
  getOpusWasmBuffer() {
    return getWasmBuffer('scripts/opus.wasm.wasm') || getWasmBuffer('opus.wasm.wasm');
  },
  getAllWasmKeys() {
    return Object.keys(WASM_MAP);
  }
};
`;

const scriptsDir = path.join(absTarget, 'scripts');
if (!fs.existsSync(scriptsDir)) {
  fs.mkdirSync(scriptsDir, { recursive: true });
}

const outPath = path.join(scriptsDir, 'embedded-wasm.js');
fs.writeFileSync(outPath, generatedCode, 'utf8');

const outputSizeKB = (Buffer.byteLength(generatedCode, 'utf8') / 1024).toFixed(1);
console.log(`[Success] 成功生成: ${path.relative(process.cwd(), outPath)} (${outputSizeKB} KB)`);
console.log(`[Audit] 原始二进制总大小: ${(totalBinaryBytes / 1024).toFixed(1)} KB, 占 4MB 主包限制的 ${((totalBinaryBytes * 1.34) / 4096 / 1024 * 100).toFixed(1)}%`);
